import streamlit as st
import pandas as pd
import numpy as np
import joblib
import json
from pathlib import Path


# ============================================================
# PAGE CONFIGURATION
# ============================================================

st.set_page_config(
    page_title="House Price Prediction",
    page_icon="🏠",
    layout="centered"
)


# ============================================================
# FILE PATHS
# ============================================================

BASE_DIR = Path(__file__).resolve().parent

MODEL_PATH = BASE_DIR / "models" / "house_price_random_forest.pkl"
LOCATIONS_PATH = BASE_DIR / "models" / "locations.json"


# ============================================================
# LOAD MODEL AND LOCATIONS
# ============================================================

@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)


@st.cache_data
def load_locations():
    with open(LOCATIONS_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


model = load_model()
locations = load_locations()


# ============================================================
# TITLE
# ============================================================

st.title("🏠 House Price Prediction")

st.write(
    "Enter the house details below to estimate its price."
)

st.divider()


# ============================================================
# USER INPUTS
# ============================================================

st.subheader("🏡 Property Information")


bathroom = st.number_input(
    "Number of Bathrooms",
    min_value=1,
    max_value=10,
    value=2,
    step=1
)


balcony = st.number_input(
    "Number of Balconies",
    min_value=0,
    max_value=10,
    value=1,
    step=1
)


carpet_area = st.number_input(
    "Carpet Area (sqft)",
    min_value=100,
    max_value=20000,
    value=1200,
    step=50
)


floor = st.number_input(
    "Floor Number",
    min_value=0,
    max_value=100,
    value=5,
    step=1
)


transaction = st.selectbox(
    "Transaction",
    [
        "Resale",
        "New Property"
    ]
)


furnishing = st.selectbox(
    "Furnishing",
    [
        "Unfurnished",
        "Semi-Furnished",
        "Furnished",
        "Unknown"
    ]
)


facing = st.selectbox(
    "Facing",
    [
        "East",
        "West",
        "North",
        "South",
        "North-East",
        "North-West",
        "South-East",
        "South-West",
        "Unknown"
    ]
)


ownership = st.selectbox(
    "Ownership",
    [
        "Freehold",
        "Leasehold",
        "Power Of Attorney",
        "Unknown"
    ]
)


location = st.selectbox(
    "Location",
    locations
)


st.divider()


# ============================================================
# PREDICTION
# ============================================================

if st.button(
    "🔮 Predict House Price",
    use_container_width=True
):

    new_house = pd.DataFrame({
        "Bathroom": [bathroom],
        "Balcony": [balcony],
        "carpet_area_sqft": [carpet_area],
        "floor_num": [floor],
        "Transaction": [transaction],
        "Furnishing": [furnishing],
        "facing": [facing],
        "Ownership": [ownership],
        "location_grouped": [location]
    })


    # Predict in log scale
    prediction_log = model.predict(new_house)


    # Convert back to original price
    predicted_price = np.expm1(prediction_log)[0]


    # Display result
    st.success("Prediction completed successfully!")


    st.metric(
        label="🏠 Estimated House Price",
        value=f"₹ {predicted_price:,.2f}"
    )


    st.info(
        "This value is an estimated price generated by the trained "
        "Random Forest machine learning model."
    )


# ============================================================
# FOOTER
# ============================================================

st.divider()

st.caption(
    "House Price Prediction System | Machine Learning Project"
)